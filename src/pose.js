// Инерциализация переходов: смена клипа БЕЗ смешивания двух движений.
//
// ЗАЧЕМ. До этого модуля любой не-шаговый клип (удар, пас, подкат, вбрасывание)
// въезжал через МЕНЕДЖЕР ВЕСОВ: вес одноразового клипа рос от нуля со скоростью
// 16 1/с, а шаговые ступени на столько же гасли. Замер показал, почему это
// давало «робот пихает мяч ногой»:
//
//   вес 0.9 набирается за 8 кадров (0.133 с), вес 0.99 — за 15 кадров (0.25 с);
//   а весь клип паса `kick_r` длится 6 кадров (0.100 с), тычок `toe` — 3.4 кадра.
//
// То есть удар РИСОВАЛСЯ ПОЛОВИНОЙ АМПЛИТУДЫ и заканчивался раньше, чем успевал
// набрать вес: нога проходила половину дуги, потом клип обрывался и поза прыгала
// обратно в бег.
//
// ЧТО ВМЕСТО. Приём из движков AAA (inertialization, Bollo, GDC 2018): новый
// клип включается СРАЗУ НА ПОЛНЫЙ ВЕС, а разрыв поз не размазывается вторым
// клипом, а гасится ЗАТУХАЮЩЕЙ ПОПРАВКОЙ поверх результата. Разница
// принципиальная, а не косметическая:
//
//   смешивание весами — на экране СРЕДНЕЕ ДВУХ ДВИЖЕНИЙ (полубег-полуудар),
//   инерциализация    — на экране ЦЕЛЬНОЕ движение, а память о прошлой позе
//                       живёт отдельным затухающим слагаемым.
//
// ГЛАВНАЯ ГРАБЛЯ, И ОНА СТОИЛА ЗАМЕРА. Первая редакция просто держала поправку
// полной в первом кадре перехода — то есть на экране оставалась РОВНО прошлая
// поза. Поза при этом непрерывна, а СКОРОСТЬ обнуляется на кадр и в следующем
// кадре прыгает к скорости нового клипа. Стенд tools/anim-rig.js (он меряет
// вторую производную угла кости) сказал прямо: доля дёрганых кадров выросла
// с 9.02 % до 11.39 %, а у клипов удара — с 26 % до 42 %. Сшивать надо не позу,
// а СКОРОСТЬ: непрерывность позы получается из неё бесплатно, наоборот — нет.
//
// Поэтому переход идёт так:
//   кадр 0: на экране ПРОДОЛЖЕНИЕ прошлого движения (прошлая поза, повёрнутая
//           на прошлую же угловую скорость) — скорость непрерывна по построению;
//   кадр 1: теперь известны две позы нового клипа подряд, то есть его скорость.
//           Считаем поправку и её производную и запускаем затухание кубическим
//           Эрмитом: он гарантирует и нужную скорость на входе, и НОЛЬ скорости
//           на выходе — то есть стык не слышен ни в начале, ни в конце.
//
// ПОЧЕМУ ШАГОВЫЕ СТУПЕНИ ОСТАЮТСЯ НА ВЕСАХ. Ходьба, бег и спринт — это ОДНА
// хореография с разным размахом (см. src/anim.js), их среднее осмысленно и даёт
// честную промежуточную походку. Инерциализация нужна там, где хореографии
// РАЗНЫЕ: удар против бега, подкат против бега, шаг влево против шага вправо.
//
// ЦЕНА. Пока переход не идёт — только перекладывание истории поз (два копирования
// кватерниона на кость). Во время перехода — несколько векторных операций на
// кость, то есть меньше, чем стоит одна причёска.

import * as THREE from 'three';
import { CONFIG } from './config.js';

const _qA = new THREE.Quaternion();
const _qB = new THREE.Quaternion();
const _vA = new THREE.Vector3();
const _vB = new THREE.Vector3();

// Потолок «скорости прошлого хода», рад/кадр (~34°). Быстрее ни одна кость в
// наших клипах не идёт: спринт даёт по бедру около 15°/кадр.
const MAX_STEP = 0.6;

// Логарифм кватерниона: поворот → вектор «ось × угол». Знак приводим к
// кратчайшей дуге, иначе поворот на 350° читается как поворот на 350°, а не
// на −10°, и поправка уезжает в обратную сторону через весь круг.
function logQuat(q, out) {
  let { x, y, z, w } = q;
  if (w < 0) { x = -x; y = -y; z = -z; w = -w; }
  const s = Math.hypot(x, y, z);
  if (s < 1e-8) return out.set(0, 0, 0);
  const ang = 2 * Math.atan2(s, w);
  return out.set(x, y, z).multiplyScalar(ang / s);
}

// Экспонента: вектор «ось × угол» → кватернион
function expQuat(v, out) {
  const ang = v.length();
  if (ang < 1e-8) return out.set(0, 0, 0, 1);
  const s = Math.sin(ang * 0.5) / ang;
  return out.set(v.x * s, v.y * s, v.z * s, Math.cos(ang * 0.5));
}

export class PoseBlend {
  constructor(model) {
    this.bones = [];
    model.traverse((o) => { if (o.isBone) this.bones.push(o); });
    const n = this.bones.length;
    const quats = () => Array.from({ length: n }, () => new THREE.Quaternion());
    const vecs = () => Array.from({ length: n }, () => new THREE.Vector3());
    // История ВЫХОДНОЙ позы: нужны два прошлых кадра, чтобы знать не только
    // позу на миг переключения, но и скорость, с которой она туда ехала
    this.h1 = quats();
    this.h2 = quats();
    this.p1 = vecs();
    this.p2 = vecs();
    this.hist = 0;                 // сколько кадров истории накоплено
    // Поза нового клипа на кадре 0 перехода — из неё на кадре 1 берём его скорость
    this.tgt0 = quats();
    this.tp0 = vecs();
    // Поправка и её производная (в логарифмическом пространстве, на кадр)
    this.x0 = vecs();
    this.v0 = vecs();
    this.px0 = vecs();
    this.pv0 = vecs();
    this.w0 = vecs();              // зажатая скорость прошлого хода, рад/кадр
    this.pw0 = vecs();             // и то же для положения таза
    this.phase = 'off';            // off | warm | seed | decay
    this.frames = 0;               // длительность затухания, кадров
    this.m = 0;                    // текущий шаг затухания
    this.tracked = false;          // позу этого кадра уже запомнили
  }

  // Запомнить выходную позу кадра. Вызывать РАЗ В КАДР в самом начале работы с
  // анимацией — тогда в костях ещё стоит итог прошлого кадра.
  //
  // Защёлка `tracked` не формальность: решение сменить клип принимает игровая
  // логика, и она работает РАНЬШЕ анимационного кадра (playOneShot зовут из
  // update/aiUpdate, а смену направления — уже из updateLoco). Порядок вызовов
  // поэтому разный, и begin() зовёт track() сам; без защёлки история сдвинулась
  // бы дважды за кадр, и «скорость прошлого кадра» стала бы скоростью за два.
  track() {
    if (this.tracked) return;
    this.tracked = true;
    const b = this.bones;
    for (let i = 0; i < b.length; i++) {
      this.h2[i].copy(this.h1[i]);
      this.h1[i].copy(b[i].quaternion);
      this.p2[i].copy(this.p1[i]);
      this.p1[i].copy(b[i].position);
    }
    if (this.hist < 2) this.hist++;
  }

  // Зарядить переход. Вызывать ДО mixer.update того кадра, в котором меняется
  // клип, и обязательно ПОСЛЕ track() этого же кадра.
  begin(dur) {
    this.track();
    if (!(dur > 0) || this.hist < 2) return;
    // Перезапуск перехода, который только начался, ЗАПРЕЩЁН. Первые два кадра
    // (warm и seed) — это разгон: в них поза ещё держится на предсказании, и
    // если поверх начать новый переход, предсказание построится на предсказании
    // и пойдёт вразнос. Такое случается на реальном поле сплошь и рядом: игрок
    // меняет направление и в том же кадре получает пас.
    if (this.phase === 'warm' || this.phase === 'seed') return;
    this.frames = Math.max(2, Math.round(dur * 60));
    this.m = 0;
    this.phase = 'warm';
  }

  // Наложить поправку. Вызывать СРАЗУ ПОСЛЕ mixer.update.
  apply() {
    this.tracked = false;          // кадр закончился, следующий снова запомнит позу
    if (this.phase === 'off') return false;
    const b = this.bones;

    // --- Кадр 0: показываем ПРОДОЛЖЕНИЕ прошлого движения ---
    // Скорость на экране не меняется вовсе, поэтому шва нет по построению.
    // Заодно прячем позу нового клипа: на следующем кадре из неё получится
    // его собственная скорость, без которой затухание сшить нечем.
    if (this.phase === 'warm') {
      for (let i = 0; i < b.length; i++) {
        this.tgt0[i].copy(b[i].quaternion);
        this.tp0[i].copy(b[i].position);
        // Прошлая угловая скорость: h1 относительно h2. Зажим не украшательство:
        // если прошлый кадр сам был кадром перехода или телепортом, ω бывает
        // огромной, и продолжение движения выстреливает фигуру в узел (замер
        // до зажима: пик 178.7°/кадр² на back_slow).
        logQuat(_qA.copy(this.h1[i]).multiply(_qB.copy(this.h2[i]).invert()), _vA);
        const len = _vA.length();
        if (len > MAX_STEP) _vA.multiplyScalar(MAX_STEP / len);
        this.w0[i].copy(_vA);
        expQuat(_vA, _qA);
        b[i].quaternion.copy(_qA).multiply(this.h1[i]);
        _vB.copy(this.p1[i]).sub(this.p2[i]);
        this.pw0[i].copy(_vB);
        b[i].position.copy(this.p1[i]).add(_vB);
      }
      this.phase = 'seed';
      return true;
    }

    // --- Кадр 1: скорость нового клипа известна — строим кривую затухания ---
    // Поправка меряется относительно позы клипа В КАДРЕ 0 (tgt0), а не текущей:
    // именно её мы в кадре 0 и подменяли. Первая редакция делила на текущую, и
    // затухание стартовало со сдвигом на кадр.
    if (this.phase === 'seed') {
      for (let i = 0; i < b.length; i++) {
        expQuat(this.w0[i], _qA);                                  // ω прошлого хода
        _qA.multiply(this.h1[i]);                                  // поза кадра 0
        _qA.multiply(_qB.copy(this.tgt0[i]).invert());             // ÷ поза клипа в кадре 0
        logQuat(_qA, this.x0[i]);
        // производная поправки = (скорость прошлого движения) − (скорость клипа)
        logQuat(_qA.copy(b[i].quaternion).multiply(_qB.copy(this.tgt0[i]).invert()), _vB);
        this.v0[i].copy(this.w0[i]).sub(_vB);
        // то же для положения таза
        this.px0[i].copy(this.p1[i]).add(this.pw0[i]).sub(this.tp0[i]);
        _vB.copy(b[i].position).sub(this.tp0[i]);
        this.pv0[i].copy(this.pw0[i]).sub(_vB);
      }
      this.phase = 'decay';
      // Кадр 0 — это шаг m = 0 той же кривой (там она равна x0, и мы её уже
      // показали). Сейчас идёт кадр 1, значит и шаг первый: если снова взять
      // нулевой, поза застынет на ДВА кадра, а это ровно тот дефект, ради
      // которого всё и переписывалось.
      this.m = 1;
    } else {
      this.m++;
    }

    const N = this.frames;
    if (this.m >= N) { this.phase = 'off'; return false; }
    // Кубический Эрмит: x(0) = x0, x'(0) = v0, x(N) = 0, x'(N) = 0.
    // Именно два последних условия и делают выход из перехода беззвучным —
    // линейное затухание оставляет излом ровно в кадре, где поправка кончилась.
    const s = this.m / N;
    const h00 = 2 * s * s * s - 3 * s * s + 1;
    const h10 = s * s * s - 2 * s * s + s;
    const kv = N * h10;
    for (let i = 0; i < b.length; i++) {
      _vA.copy(this.x0[i]).multiplyScalar(h00).addScaledVector(this.v0[i], kv);
      if (_vA.lengthSq() > 1e-12) {
        expQuat(_vA, _qA);
        b[i].quaternion.premultiply(_qA);
      }
      _vB.copy(this.px0[i]).multiplyScalar(h00).addScaledVector(this.pv0[i], kv);
      if (_vB.lengthSq() > 1e-12) b[i].position.add(_vB);
    }
    return true;
  }

  // Телепорт (розыгрыш с центра, смена ракурса повтора): память о прошлой позе
  // становится ложью — гасим. Та же логика, что у пружины волос в src/hair.js.
  reset() {
    this.phase = 'off';
    this.hist = 0;
    this.m = 0;
    this.tracked = false;
  }

  get active() {
    return this.phase !== 'off';
  }
}

// Длительность перехода под вид смены. Все числа — в CONFIG.player.anim.blend,
// здесь только выбор.
export function blendTime(kind) {
  const B = CONFIG.player.anim.blend;
  return B[kind] != null ? B[kind] : B.def;
}
